import type { Creator } from "@/types/domain";
import { media } from "./builders";

type Seed = Omit<Creator, "id" | "userId" | "portrait" | "cover" | "atelier" | "followingCreatorIds"> & {
  following?: string[];
};

function creator(s: Seed): Creator {
  const { following = [], ...rest } = s;
  return {
    ...rest,
    id: `cr-${s.slug}`,
    userId: `usr-${s.slug}`,
    portrait: media(`portrait-${s.slug}`, `Portrait de ${s.realName}`, "portrait"),
    cover: media(`cover-${s.slug}`, `Univers de ${s.brandName}`, "cover"),
    atelier: media(`atelier-${s.slug}`, `L'atelier de ${s.brandName}`, "atelier"),
    followingCreatorIds: following.map((slug) => `cr-${slug}`),
  };
}

